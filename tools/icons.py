#!/usr/bin/env python3
"""Convert the SVG icons in icons/ to path data in qml/IconPaths.js.

QtQuick.Shapes draws path data in any colour, so the app needs no SVG module.
Usage: icons.py [--check]   --check exits with 1 if qml/IconPaths.js is out of date.
"""
import argparse
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "qml" / "IconPaths.js"
NS = "{http://www.w3.org/2000/svg}"


def num(value):
    """Format a number without a useless fraction: 2.0 becomes 2."""
    return f"{float(value):g}"


def absolute_start(d):
    """Make the first move of a path absolute, so paths can be joined.

    A path that starts with "m" moves from the origin. After a join it would
    move from the end of the path before it. The pairs after the first one
    are relative lines, so they keep a lowercase "l".
    """
    number = r"([-+]?(?:\d+\.?\d*|\.\d+))"
    match = re.match(rf"\s*m\s*{number}[\s,]*{number}[\s,]*(.*)", d, re.S)
    if match is None:
        return d
    x, y, rest = match.groups()
    if rest and (rest[0].isdigit() or rest[0] in "-."):
        rest = "l" + rest
    return f"M{x} {y}{rest}"


def to_path(element):
    tag = element.tag.removeprefix(NS)
    geometry = ("cx", "cy", "r", "x", "y", "width", "height", "rx", "ry")
    a = {k: float(v) for k, v in element.attrib.items() if k in geometry}
    if tag == "path":
        return absolute_start(element.attrib["d"])
    if tag == "circle":
        cx, cy, r = a["cx"], a["cy"], a["r"]
        return (f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0"
                f"a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0")
    if tag == "rect":
        x, y, w, h = a.get("x", 0), a.get("y", 0), a["width"], a["height"]
        rx = a.get("rx", a.get("ry", 0))
        ry = a.get("ry", rx)
        if rx == 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
        return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}v{num(h - 2 * ry)}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}h{num(2 * rx - w)}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}v{num(2 * ry - h)}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}z")
    raise ValueError(f"unsupported SVG element <{tag}>")


def icon_path(svg):
    root = ET.parse(svg).getroot()
    return " ".join(to_path(e) for e in root if e.tag != f"{NS}title")


def render():
    paths = {svg.stem: icon_path(svg) for svg in sorted((ROOT / "icons").glob("*.svg"))}
    # Qt needs ".pragma library" on the first line.
    lines = [
        ".pragma library",
        "// Generated by tools/icons.py from icons/*.svg. Do not edit.",
        "// The icons come from Lucide, under the ISC licence in icons/LICENSE.",
        "",
        "var paths = {",
        *(f"    {json.dumps(name)}: {json.dumps(d)}," for name, d in paths.items()),
        "};",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        text = render()
    except (ValueError, KeyError, ET.ParseError) as error:
        print(f"icons: {error}", file=sys.stderr)
        return 2
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("icons: qml/IconPaths.js is out of date. Run tools/icons.py.", file=sys.stderr)
            return 1
        print("icons: qml/IconPaths.js is up to date")
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
